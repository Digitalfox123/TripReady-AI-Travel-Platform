export function getDishImage(dishName, cityName = '') {
  if (!dishName) {
    return 'https://images.unsplash.com/photo-1504674900247-0877df9cc836?w=700&q=80';
  }

  const cleanDish = dishName.toLowerCase().replace(/[^a-z0-9]/g, '');

  // Direct exact match
  for (const [key, url] of Object.entries(DISH_IMAGE_REGISTRY)) {
    if (cleanDish.includes(key) || key.includes(cleanDish)) {
      return url;
    }
  }

  // Keyword-based smart culinary matching
  if (cleanDish.includes('noodle') || cleanDish.includes('soba') || cleanDish.includes('udon') || cleanDish.includes('ramen')) {
    return DISH_IMAGE_REGISTRY.ramen;
  }
  if (cleanDish.includes('tofu') || cleanDish.includes('yuba')) {
    return DISH_IMAGE_REGISTRY.yuba;
  }
  if (cleanDish.includes('tea') || cleanDish.includes('sweet') || cleanDish.includes('pastry') || cleanDish.includes('dessert') || cleanDish.includes('cake')) {
    return DISH_IMAGE_REGISTRY.matcha;
  }
  if (cleanDish.includes('rice') || cleanDish.includes('biryani') || cleanDish.includes('pilaf') || cleanDish.includes('paella')) {
    return DISH_IMAGE_REGISTRY.paella;
  }
  if (cleanDish.includes('meat') || cleanDish.includes('beef') || cleanDish.includes('steak') || cleanDish.includes('grill') || cleanDish.includes('skewer')) {
    return DISH_IMAGE_REGISTRY.yakitori;
  }
  if (cleanDish.includes('fish') || cleanDish.includes('seafood') || cleanDish.includes('perch') || cleanDish.includes('salmon') || cleanDish.includes('prawn')) {
    return DISH_IMAGE_REGISTRY.perche;
  }
  if (cleanDish.includes('soup') || cleanDish.includes('stew') || cleanDish.includes('broth') || cleanDish.includes('fondue')) {
    return DISH_IMAGE_REGISTRY.fondue;
  }
  if (cleanDish.includes('cheese') || cleanDish.includes('pizza')) {
    return DISH_IMAGE_REGISTRY.pizza;
  }
  if (cleanDish.includes('bread') || cleanDish.includes('bakery') || cleanDish.includes('croissant')) {
    return DISH_IMAGE_REGISTRY.croissant;
  }

  // City-specific fallback
  const cleanCity = cityName.toLowerCase();
  if (cleanCity.includes('kyoto') || cleanCity.includes('tokyo') || cleanCity.includes('osaka') || cleanCity.includes('japan')) {
    return DISH_IMAGE_REGISTRY.kaiseki;
  }
  if (cleanCity.includes('paris') || cleanCity.includes('nice') || cleanCity.includes('france')) {
    return DISH_IMAGE_REGISTRY.croissant;
  }
  if (cleanCity.includes('rome') || cleanCity.includes('milan') || cleanCity.includes('italy')) {
    return DISH_IMAGE_REGISTRY.pizza;
  }
  if (cleanCity.includes('geneva') || cleanCity.includes('zurich') || cleanCity.includes('switzerland')) {
    return DISH_IMAGE_REGISTRY.fondue;
  }
  if (cleanCity.includes('lahore') || cleanCity.includes('karachi') || cleanCity.includes('pakistan')) {
    return DISH_IMAGE_REGISTRY.karahi;
  }

  return 'https://images.unsplash.com/photo-1504674900247-0877df9cc836?w=700&q=80';
}
